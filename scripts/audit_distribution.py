"""Reproduce the private Issue #11 inventory at two immutable source revisions."""
import argparse
import json
from pathlib import Path
import re
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from engineering_kit.sync import bundle_read, digest, encoded, export

KIT = 'e647d9d535eb9b55f2a6df55c2bf5e4b9a47957d'
TEMPLATE = '0a53f56dba841675b3203a76e33594fee1a73b9f'
FINDINGS = {
    '.engineering-kit/contract/AGENT_COMMON.md': ('REDACT/REFACTOR',
        'Frozen legacy policy; relative .github entrypoint resolves outside installed namespace. Require explicit provenance-only use and consumer link review.'),
    '.engineering-kit/contract/DEVELOPMENT_INTERFACE.md': ('REDACT/REFACTOR',
        'Historical codex-smart Issue #169 URL, named products/platforms and legacy duplicate lifecycle; review disclosure and relocated relative links without changing frozen v0.1 bytes.'),
    '.engineering-kit/skills/ek-context/SKILL.md': ('PUBLIC-SAFE',
        'Generic instruction-only reference; pinned contract means consumer-selected active Template policy. No implicit skill activation.'),
    '.engineering-kit/skills/ek-verify/SKILL.md': ('REDACT/REFACTOR',
        'Names RelayForge legacy live Cargo path. Owner must review disclosure or refactor technical source in Kit.'),
    '.engineering-kit/skills/ek-pr-closeout/SKILL.md': ('PUBLIC-SAFE',
        'Generic instruction-only review/cleanup rules; no executable hooks.'),
    '.engineering-kit/PROFILE.md': ('PUBLIC-SAFE',
        'Minimal profile, local AGENTS first; no installations or commands.'),
    'AGENTS.md': ('PUBLIC-SAFE',
        'Requires consumer docs/INDEX.md and AGENTS.local.md outside managed set; verify these before adoption. Existing root entrypoint must collide.'),
    '.github/DEVELOPMENT_INTERFACE.md': ('REDACT/REFACTOR',
        'Canonical owner metadata is intended provenance; names RelayForge runtime. Review disclosure before classifying source bytes.'),
    '.github/ISSUE_TEMPLATE/task.yml': ('PUBLIC-SAFE',
        'Generic Task form metadata; no server labels, scripts or administrative mutations.'),
    '.github/pull_request_template.md': ('PUBLIC-SAFE',
        'Generic evidence template; no prefilled private IDs or credentials.'),
    'docs/WORKFLOW.md': ('REDACT/REFACTOR',
        'UPGRADING.md, PROJECT.md and AGENTS.local.md are external consumer prerequisites. UPGRADING.md currently describes private-only delivery; reconcile canonical instructions before public adoption.'),
    '.project-template/OWNERSHIP.md': ('REDACT/REFACTOR',
        'Explicit both-distributions-private policy; cannot silently relabel or redact generated bytes. Requires canonical Template review and new independently versioned source.'),
}


def inventory(kit_source, template_source):
    rows = []
    with tempfile.TemporaryDirectory(prefix='ek-audit-') as directory:
        for channel, source, revision, profile in (
                ('kit', kit_source, KIT, 'minimal'),
                ('admin', template_source, TEMPLATE, 'administrative')):
            bundle = Path(directory) / (channel + '.json')
            export(source, revision, profile, bundle, channel)
            manifest, contents = bundle_read(bundle, channel)
            for name, data in sorted(contents.items()):
                classification, finding = FINDINGS[name]
                text = data.decode('utf-8')
                rows.append({'channel': channel, 'destination': name,
                    'source': ('profiles/sync/minimal.md' if name == '.engineering-kit/PROFILE.md'
                               else name.removeprefix('.engineering-kit/') if channel == 'kit' else name),
                    'upstream': revision, 'sha256': digest(data), 'bytes': len(data),
                    'classification': classification, 'finding': finding,
                    'markdown_links': re.findall(r'\]\(([^)]+)\)', text),
                    'frontmatter': text.split('---', 2)[1].strip() if text.startswith('---\n') else None,
                    'release_gate': 'BLOCKED: no owner authorization or selected redistribution license'})
    return {'format': 1, 'purpose': 'Private staging audit; not a PUBLIC-SAFE release review',
            'kit_admin_implementation': '21cf2914cb0a1c904ca8c783a36723786373b600',
            'profile': 'minimal; other profiles need a new exact-byte audit',
            'files': rows}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--kit-source', type=Path, default=Path('.'))
    parser.add_argument('--template-source', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = encoded(inventory(args.kit_source, args.template_source))
    if args.check:
        if args.output.read_bytes() != data:
            raise SystemExit('audit differs from pinned sources')
    else:
        with args.output.open('xb') as stream:
            stream.write(data)
    print(json.dumps({'files': 12, 'audit_sha256': digest(data), 'check': args.check}))


if __name__ == '__main__':
    main()
